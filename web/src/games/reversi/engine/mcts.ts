/** The most-visited move. Ties go to the lower index, so this is deterministic. */
export function bestAction(result: SearchResult): Action {
  let best = 0;
  for (let i = 1; i < result.actions.length; i++) {
    if (result.visits[i]! > result.visits[best]!) best = i;
  }
  return result.actions[best]!;
}

/** The search's estimate for the player to move at the root, in [-1, 1]. */
export function searchValue(result: SearchResult): number {
  let total = 0;
  for (const n of result.visits) total += n;
  if (total === 0) return result.rootValue;

  let weighted = 0;
  for (let i = 0; i < result.visits.length; i++) {
    weighted += result.qValues[i]! * result.visits[i]!;
  }
  return weighted / total;
}

/** Full-width visit counts, for the heat map. Zero on every illegal action. */
export function visitCounts(result: SearchResult): number[] {
  const counts = new Array<number>(result.boardSize * result.boardSize + 1).fill(0);
  result.actions.forEach((action, index) => {
    counts[action] = result.visits[index]!;
  });
  return counts;
}
