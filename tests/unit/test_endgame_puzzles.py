class TestStages:
    def test_the_bands_are_ordered_and_do_not_overlap(self) -> None:
        """Stages have to partition the empty counts, or a position has two homes.

        Overlapping bands would let two puzzles of the same size land in
        different stages, which quietly destroys the one thing the progression
        promises: that later stages are bigger positions.
        """
        assert [stage.number for stage in STAGES] == list(range(1, len(STAGES) + 1))
        for earlier, later in pairwise(STAGES):
            assert earlier.low <= earlier.high
            assert earlier.high < later.low

    def test_every_count_in_range_belongs_to_exactly_one_stage(self) -> None:
        lowest, highest = STAGES[0].low, STAGES[-1].high
        for open_squares in range(lowest, highest + 1):
            matches = [stage for stage in STAGES if stage.contains(open_squares)]
            assert len(matches) == 1
            assert stage_for(open_squares) is matches[0]

    def test_a_position_outside_every_band_has_no_stage(self) -> None:
        assert stage_for(STAGES[0].low - 1) is None
        assert stage_for(STAGES[-1].high + 1) is None


