def _five_empty_position() -> State:
    """A position that ends before the board is full, played out by random moves.

    Built rather than written down, because a hand-typed board is one transposed
    row away from testing nothing. The requirement is a game whose perfect play
    leaves empty squares -- that is what makes the two scoring conventions
    disagree, which is what these tests are about.
    """
    rng = np.random.default_rng(7)
    for _ in range(500):
        state = rules.initial_state(8)
        while not rules.is_terminal(state) and empties(state) > 5:
            legal = rules.legal_actions(state)
            state = rules.apply(state, int(legal[rng.integers(0, len(legal))]))
        if rules.is_terminal(state) or empties(state) != 5:
            continue
        skip = pass_action(8)
        if len([a for a in rules.legal_actions(state) if a != skip]) < 2:
            continue
        if solve_root(state).margins != solve_root(state, empties_to_winner=True).margins:
            return state
    raise AssertionError("no position found where the two scoring conventions differ")


def _puzzle_stub(state: State, edax: RootSolution) -> Puzzle:
    """A puzzle built from a solve rather than from mining.

    ``write_obf`` reads two of these fields. Mining a real puzzle here would cost
    a minute and a loaded network to test a string format.
    """
    solution = solve_root(state)
    return Puzzle(
        stage=1,
        state=state,
        empties=empties(state),
        margins=dict(solution.margins),
        best=solution.best,
        best_moves=solution.best_moves,
        winning_moves=solution.winning_moves,
        principal_variation=solution.principal_variation,
        edax_margins=dict(edax.margins),
        tempting_move=solution.best_moves[0],
        tempting_margin=solution.best,
        trap_mass=0.0,
        greedy_falls=False,
        difficulty=0,
        nodes=solution.nodes,
    )


def test_square_names_round_trip_through_the_problem_format() -> None:
    """``19`` is D3 both ways, or every score in the file is against a wrong move."""
    for action in range(64):
        assert square_index(square_name(action)) == action
