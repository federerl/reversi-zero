class TestShippedCurriculum:
    def test_the_file_matches_its_own_schema(self) -> None:
        payload = load_fixture()
        assert payload["fixture"] == "puzzles"
        assert payload["cases"], "the curriculum is empty"
        width = len(payload["schema"])
        for case in payload["cases"]:
            assert len(case) == width

    def test_boards_are_hex_strings_and_not_numbers(self) -> None:
        """A 64-bit board is not exact as a JSON number. Ports fail quietly on it."""
        payload = load_fixture()
        for row in rows(payload):
            assert isinstance(row["black_hex"], str)
            assert isinstance(row["white_hex"], str)
            int(row["black_hex"], 16)
            int(row["white_hex"], 16)

    def test_every_puzzle_is_winnable_and_offers_a_choice(self) -> None:
        payload = load_fixture()
        skip = pass_action(payload["board_size"])
        for row in rows(payload):
            state = state_of_row(row, payload["board_size"])
            placements = [a for a in rules.legal_actions(state) if a != skip]
            assert row["best"] > 0, "a position nobody can win is not a puzzle"
            assert len(placements) >= 2, "a forced move is not a puzzle"
            assert len(row["margins"]) == len(placements)

    def test_every_puzzle_has_a_way_to_go_wrong(self) -> None:
        """The selection rule, read back off the shipped file.

        A position where every move wins has no wrong answer, and one where the
        losing moves are unattractive teaches nothing. Either the network's first
        choice loses, or grabbing the most discs does.
        """
        payload = load_fixture()
        for row in rows(payload):
            margins = dict(row["margins"])
            losing = [move for move, margin in margins.items() if margin <= 0]
            assert losing, "every move wins, so there is nothing to get wrong"
            tempted = margins[row["tempting"]] <= 0
            assert tempted or row["greedy_falls"], "the losing moves are not tempting"

    def test_every_puzzle_sits_inside_its_stage_s_band(self) -> None:
        payload = load_fixture()
        bands = {stage["stage"]: stage["empties"] for stage in payload["stages"]}
        for row in rows(payload):
            state = state_of_row(row, payload["board_size"])
            low, high = bands[row["stage"]]
            assert row["empties"] == empties(state)
            assert low <= row["empties"] <= high

    def test_the_file_is_already_in_presentation_order(self) -> None:
        """This is the test that keeps it a progression rather than a sorted pile.

        The app reads the file top to bottom. If the generator ever stops
        ordering it, the curriculum silently becomes a shuffle while every other
        test here still passes.
        """
        payload = load_fixture()
        listed = [row["stage"] for row in rows(payload)]
        assert listed == sorted(listed)

        for stage in payload["stages"]:
            within = [row["difficulty"] for row in rows(payload) if row["stage"] == stage["stage"]]
            assert within == sorted(within), f"stage {stage['stage']} is out of order"

    def test_stage_metadata_matches_the_curriculum_in_code(self) -> None:
        payload = load_fixture()
        by_number = {stage.number: stage for stage in STAGES}
        for listed in payload["stages"]:
            stage = by_number[listed["stage"]]
            assert listed["empties"] == [stage.low, stage.high]
            assert listed["title"] == stage.title


class TestShippedAnswers:
    """Re-solving the shipped puzzles. The check a wrong file cannot survive."""

    def _verify(self, row: dict, board_size: int) -> None:
        state = state_of_row(row, board_size)
        solution = solve_root(state)

        assert dict(row["margins"]) == solution.margins
        assert row["best"] == solution.best
        assert row["difficulty"] >= 0

        # And the stored line of play really reaches the stored score, so the
        # replay a player is shown after a correct answer is not a decoration.
        played = state
        for action in row["pv"]:
            played = rules.apply(played, action)
        assert rules.is_terminal(played)
        black, white = scoring.disc_counts(played)
        mine, theirs = (black, white) if state.to_move is Player.BLACK else (white, black)
        assert mine - theirs == row["best"]

    def test_the_small_stages_are_exactly_what_the_solver_says(self) -> None:
        payload = load_fixture()
        checked = [row for row in rows(payload) if row["empties"] <= FAST_LANE_EMPTIES]
        assert checked, "no puzzle small enough for the fast lane"
        for row in checked:
            self._verify(row, payload["board_size"])

    @pytest.mark.slow
    @pytest.mark.timeout(1800)
    def test_every_shipped_puzzle_is_exactly_what_the_solver_says(self) -> None:
        payload = load_fixture()
        for row in rows(payload):
            self._verify(row, payload["board_size"])


