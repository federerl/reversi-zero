"""The puzzle curriculum: how it is derived, and whether the shipped file is true.

Two different jobs here, and the second one is the important one.

The first is ordinary: the selection rule and the difficulty score are code, and
code needs tests. Those run against positions built by hand, so a failure points
at one function.

The second is what protects a player. ``puzzles.json`` is generated by mining --
minutes of self-play and exact solving, dependent on torch arithmetic that is not
promised to be identical on another machine -- so it cannot be checked by
regenerating it and diffing, the way the five port fixtures are. What can be
checked anywhere is whether the answers in it are *true*: every puzzle is solved
again from its board and the stored table is compared move by move.

That is the stronger check regardless. A hand-edited puzzle file is dangerous
because it would tell somebody their winning move loses, with an interface that
says the answer is certain. Re-solving catches exactly that; a diff would only
notice that the file had been touched.
"""

from __future__ import annotations

import json
from itertools import pairwise
from pathlib import Path

import numpy as np
import pytest

from reversi.agents.edax import board_string, obf_string, square_index, square_name
from reversi.endgame.puzzles import (
    STAGES,
    MiningError,
    Puzzle,
    difficulty_of,
    stage_for,
    write_obf,
)
from reversi.endgame.solver import RootSolution, empties, solve_root
from reversi.game import rules, scoring
from reversi.game.state import State
from reversi.types import Player, pass_action
from reversi.web.fixtures import state_of

FIXTURE = Path("web/src/games/reversi/engine/__fixtures__/puzzles.json")

# Puzzles at or below this many empty squares are re-solved in the fast test
# lane. Above it the solve is seconds rather than milliseconds, so the whole file
# is re-verified in the slow lane instead. Both lanes use the same code; the only
# difference is how much of the file they cover.
FAST_LANE_EMPTIES = 9


def load_fixture() -> dict:
    if not FIXTURE.exists():  # pragma: no cover - only on a fresh clone
        pytest.skip(f"{FIXTURE} has not been generated yet")
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def rows(payload: dict) -> list[dict]:
    """Fixture rows as dicts, keyed by the schema the file carries."""
    schema = payload["schema"]
    return [dict(zip(schema, case, strict=True)) for case in payload["cases"]]


def state_of_row(row: dict, board_size: int) -> State:
    return state_of(row["black_hex"], row["white_hex"], row["to_move"], board_size)


