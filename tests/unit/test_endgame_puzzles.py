class TestDifficulty:
    def test_a_narrow_win_scores_above_a_wide_one(self) -> None:
        """The dominant term, and the only one measured from the position alone.

        Same board size, same temptation: the position where one move in five
        holds the win is the harder ask.
        """
        flat = dict.fromkeys(range(5), 0.2)
        narrow = difficulty_of({0: 4, 1: -2, 2: -2, 3: -2, 4: -2}, flat, greedy=False)
        wide = difficulty_of({0: 4, 1: 4, 2: 4, 3: 4, 4: -2}, flat, greedy=False)
        assert narrow > wide

    def test_a_tempting_loss_scores_above_an_ignored_one(self) -> None:
        """A losing move nobody wants to play is not a trap."""
        margins = {0: 4, 1: -2, 2: -2, 3: -2, 4: -2}
        tempted = difficulty_of(margins, {0: 0.05, 1: 0.7, 2: 0.1, 3: 0.1, 4: 0.05}, greedy=False)
        alert = difficulty_of(margins, {0: 0.8, 1: 0.05, 2: 0.05, 3: 0.05, 4: 0.05}, greedy=False)
        assert tempted > alert

    def test_disc_grabbing_losing_adds_to_the_score(self) -> None:
        margins = {0: 4, 1: -2, 2: -2}
        policy = {0: 0.5, 1: 0.3, 2: 0.2}
        assert difficulty_of(margins, policy, greedy=True) > difficulty_of(
            margins, policy, greedy=False
        )

    def test_the_score_stays_on_its_scale(self) -> None:
        """An integer in 0-100, so a shipped order never hinges on a float compare.

        The top of the scale is reachable: one winning move, every drop of the
        network's probability resting on a loser, and disc-grabbing losing too.
        The bottom is not, and should not be -- scoring 0 would need a position
        with no losing move at all, which is by definition not a puzzle.
        """
        hardest = difficulty_of({0: 2, 1: -2}, {0: 0.0, 1: 1.0}, greedy=True)
        mildest = difficulty_of({0: 2, 1: 2, 2: -2}, {0: 0.5, 1: 0.5, 2: 0.0}, greedy=False)
        assert hardest == 100
        assert isinstance(hardest, int)
        assert 0 < mildest < hardest

    def test_it_refuses_a_position_that_is_not_a_puzzle(self) -> None:
        """No win, or no choice, means there is nothing to be difficult about."""
        with pytest.raises(MiningError, match="winnable"):
            difficulty_of({0: -2, 1: -4}, {0: 0.5, 1: 0.5}, greedy=False)
        with pytest.raises(MiningError, match="choice"):
            difficulty_of({0: 4}, {0: 1.0}, greedy=False)


