class TestObf:
    def test_the_two_notations_differ_only_in_the_letters(self) -> None:
        """``.obf`` writes X and O; Edax's own printout writes * and O.

        Worth pinning because the failure is silent: Edax reads a ``.obf`` line
        whose black discs are ``*`` as an empty board, solves that instead, and
        reports a disagreement that looks like a solver bug.
        """
        state = rules.initial_state(8)
        assert obf_string(state) == board_string(state).replace("*", "X")
        assert set(obf_string(state).split()[0]) <= {"X", "O", "-"}

    def test_a_written_line_parses_back_to_the_same_position(self, tmp_path: Path) -> None:
        state = _five_empty_position()
        solution = solve_root(state, empties_to_winner=True)
        puzzle = _puzzle_stub(state, solution)

        destination = tmp_path / "endgame.obf"
        written = write_obf(destination, [puzzle])
        line = destination.read_text(encoding="utf-8").strip()

        assert written == len(destination.read_bytes())
        board, _, scores = line.partition(";")
        squares, side = board.split()
        assert len(squares) == 64
        assert side == ("X" if state.to_move is Player.BLACK else "O")

        parsed = {}
        for item in scores.split(";"):
            if item.strip():
                name, _, margin = item.strip().partition(":")
                parsed[square_index(name)] = int(margin)
        assert parsed == solution.margins

    def test_scores_are_written_best_first(self, tmp_path: Path) -> None:
        """Edax's own problem files are ordered that way, and a reader expects it."""
        state = _five_empty_position()
        solution = solve_root(state, empties_to_winner=True)
        destination = tmp_path / "endgame.obf"
        write_obf(destination, [_puzzle_stub(state, solution)])

        _, _, scores = destination.read_text(encoding="utf-8").strip().partition(";")
        values = [int(item.split(":")[1]) for item in scores.split(";") if item.strip()]
        assert values == sorted(values, reverse=True)

    def test_the_file_carries_edax_scoring_not_this_project_s(self) -> None:
        """The whole point of the file is that Edax will check it.

        These are the only numbers in the repository written in the other
        convention, so a mix-up would make a correct solver look broken against
        the reference engine -- the exact confusion the solver's own tests were
        built to rule out.
        """
        state = _five_empty_position()
        ours = solve_root(state)
        theirs = solve_root(state, empties_to_winner=True)
        stub = _puzzle_stub(state, theirs)
        assert stub.edax_margins == theirs.margins
        # And the two conventions really are different here, or this proves nothing.
        assert ours.margins != theirs.margins


